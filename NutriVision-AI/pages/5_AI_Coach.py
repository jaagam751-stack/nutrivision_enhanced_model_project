# Result
# --------------------------------------------------------------------------- #
def render_answer() -> None:
    """Render the last answer (from session state) or the last failure."""
    answer = st.session_state.get(SESSION_ANSWER)
    error = st.session_state.get(SESSION_ERROR)
    meta = st.session_state.get(SESSION_META) or {}

    if error:
        ui.section("The coach could not answer", "Nothing is invented to fill the gap.", icon="⚠️")
        ui.notice(
            f"<strong>{error.get('label', error.get('kind', 'Error'))}</strong>: "
            f"{error.get('message', '')}",
            tone="danger",
            icon="🚫",
        )
        advice = error.get("advice")
        if advice:
            ui.notice(advice, tone="warning", icon="👉")
        st.caption(
            "Retry when the cause is resolved. Meals, dashboard, history and the forecast are "
            "unaffected — none of them depend on the coach."
        )
        return

    if not answer:
        return

    ui.section("Your coaching message", "Generated from the snapshot above.", icon="💡")
    ui.card(
        title=f"{meta.get('model', GEMINI_MODEL_NAME)} · {meta.get('created', '')}",
        icon="🤖",
        body_html=ui.html_raw(f"<div style='white-space:pre-wrap'>{_escape(answer)}</div>"),
    )
    footer_bits = []
    if meta.get("question"):
        footer_bits.append(f"Question: “{meta['question']}”")
    if meta.get("latency_ms"):
        footer_bits.append(f"{meta['latency_ms']:,} ms")
    if meta.get("total_tokens"):
        footer_bits.append(f"{meta['total_tokens']:,} tokens")
    if meta.get("saved_id"):
        footer_bits.append(f"stored as recommendation #{meta['saved_id']}")
    if footer_bits:
        st.caption(" · ".join(footer_bits))
    ui.notice(
        "This text was written by an AI model from the numbers shown above. It can be wrong or "
        "generic, it is an estimate-based suggestion, and it is <strong>not medical advice</strong>. "
        "The stored copy in the table below is what future sessions will read.",
        tone="warning",
        icon="🤖",
    )


def _escape(text: str) -> str:
    """Escape HTML so model output is never rendered as markup."""
    return (
        str(text)
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
    )


