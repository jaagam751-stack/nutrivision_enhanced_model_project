def render_no_profile() -> None:
    ui.hero(
        title="AI Coach",
        subtitle="Create your profile and save a few meals first — the coach reads your own data.",
        eyebrow="Gemini · Step 0",
        icon="🤖",
    )
    ui.notice(
        "Open the main **NutriVision AI** page from the sidebar and complete onboarding. The coach "
        "summarises your profile, your saved meals and the PNIE forecast, so it needs that data to "
        "say anything useful.",
        tone="info",
        icon="👤",
    )

    ui.page_footer(CURRENT_PHASE, APP_BUILD, APP_FOOTER_NOTE)


def main() -> None:
    init_session_state()
    ui.load_css()
    render_pending_flash()

    profile: Optional[UserProfile] = get_profile()
    if profile is None:
        render_no_profile()
        return
    if not require_database() or not require_stored_profile(profile):
        return

    user_id = int(profile.user_id)
    status = coach_status()

    ui.hero(
        title="Your AI nutrition coach",
        subtitle=(
            f"{GEMINI_MODEL_NAME} writes one short, practical message from your profile, your saved "
            f"meals and the PNIE forecast. One API call per press — you can read everything it is "
            f"given first."
        ),
        eyebrow=f"AI Coach · {status.label}",
        icon="🤖",
    )

    if not status.configured:
        render_setup_help(status)

    context = coach_context(user_id, profile, outcome=run_pnie_for_user(user_id))
    render_context_card(context, st.session_state.get(SESSION_QUESTION, ""))

    ui.section("Ask the coach", "Optional — leave it empty for a general review of your week.", icon="✍️")
    question = st.text_area(
        "Your question (optional)",
        value=st.session_state.get(SESSION_QUESTION, ""),
        placeholder="e.g. How can I get more protein without eating more rotis?",
        max_chars=400,
        height=90,
        label_visibility="collapsed",
    )
    col_a, col_b = st.columns([1, 3], gap="medium")
    with col_a:
        pressed = st.button(
            "Get my recommendation",
            type="primary",
            width="stretch",
            disabled=not status.configured,
            help=None if status.configured else status.reason,
        )
    with col_b:
        st.caption(
            f"One Gemini API call · up to {GEMINI_TARGET_WORDS} words · the answer is stored in your "
            "history. Nothing is requested until you press the button."
        )

    if pressed:
        st.session_state[SESSION_QUESTION] = question.strip()
        with st.spinner(f"Asking {GEMINI_MODEL_NAME}…"):
            outcome = request_recommendation(user_id, context, question=question)
        if outcome.ok:
            result: CoachResult = outcome.result
            st.session_state[SESSION_ANSWER] = outcome.text
            st.session_state[SESSION_ERROR] = None
            st.session_state[SESSION_META] = {
                "model": (result.model if result else "") or GEMINI_MODEL_NAME,
                "created": datetime.now(timezone.utc).strftime("%d %b %Y · %H:%M UTC"),
                "latency_ms": result.latency_ms if result else None,
                "total_tokens": result.total_tokens if result else None,
                "question": question.strip(),
                "saved_id": getattr(outcome.row, "recommendation_id", None),
            }
            flash(outcome.message, "success")
        else:
            st.session_state[SESSION_ANSWER] = None
            result = outcome.result
            st.session_state[SESSION_META] = {}
            st.session_state[SESSION_ERROR] = {
                "kind": getattr(result, "error_kind", "unknown_error"),
                "message": getattr(result, "error_message", outcome.message) or outcome.message,
                "advice": getattr(result, "advice_text", "") or ERROR_ADVICE.get("unknown_error", ""),
                "label": _error_label(getattr(result, "error_kind", "unknown_error")),
            }
            logger.warning("Coach request failed: %s", outcome.message)
        st.rerun()

    render_answer()
    st.divider()
    render_latest_stored(user_id)
    render_history(user_id)
    st.divider()
    render_privacy_note()

    ui.notice(
        "The coach is a language model, not a clinician: its message can be inaccurate or generic, "
        "and it only knows what the snapshot contains. Calorie, nutrient and health-score values are "
        "estimates from food composition tables. This is general wellness information, not medical "
        "advice — for a personal plan, see a registered dietitian or your doctor.",
        tone="warning",
        icon="⚠️",
    )

    ui.page_footer(CURRENT_PHASE, APP_BUILD, APP_FOOTER_NOTE)


def _error_label(kind: str) -> str:
    labels = {
        "not_configured": "Not configured",
        "sdk_missing": "Library missing",
        "invalid_key": "API key rejected",
        "permission_denied": "Permission denied",
        "model_not_found": "Model unavailable",
        "quota_exceeded": "Quota or rate limit reached",
        "server_error": "Google's service error",
        "timeout": "Request timed out",
        "network_error": "Network problem",
        "blocked": "Answer blocked by safety filters",
        "empty_response": "Empty answer",
        "unknown_error": "Unexpected error",
    }
    return labels.get(kind, kind.replace("_", " ").title())


main()
