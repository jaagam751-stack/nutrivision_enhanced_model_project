def render_context_card(context, question: str) -> None:
    """Show the snapshot the coach will receive, plus the exact prompt."""
    ui.section(
        "What the coach will see",
        "Built from your profile, your saved meals and the PNIE forecast — nothing else.",
        icon="👀",
    )
    left, right = st.columns([1, 1], gap="large")
    with left:
        ui.stat_rows(context.as_rows())
    with right:
        if context.recent_meals:
            rows = [
                (
                    meal.get("when") or "—",
                    f"{meal.get('food', 'food')} · {meal.get('grams', 0):,.0f} g · "
                    f"{meal.get('calories', 0):,.0f} kcal",
                )
                for meal in context.recent_meals
            ]
            ui.stat_rows(rows)
        else:
            ui.notice(
                "No meals saved yet — the coach will give general guidance from your profile and "
                "explain that intake history is missing.",
                tone="info",
                icon="🍽️",
            )

    for note in context.notes:
        ui.notice(note, tone="info", icon="📝")

    with st.expander("Read the exact prompt that will be sent"):
        st.code(context.to_prompt(question), language="text")


