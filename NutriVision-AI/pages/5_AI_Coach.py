"""AI Coach — Gemini 2.5 Flash nutrition guidance (Phase 7).

The page is transparent by design:

* it shows **exactly what the coach will see** (the same snapshot that is sent),
  and the raw prompt can be expanded and read;
* it makes **one** API call, and only when you press the button — nothing is
  requested on page load, so quota is never spent on reruns;
* it reports **why** nothing was shown when a call fails (bad key, quota, timeout,
  network, blocked answer) together with what to do about it, and it never
  substitutes canned advice for a missing answer;
* every answer is stored in the ``recommendations`` table with its model name,
  so AI text is always traceable and never mixed up with the rule-based engine.

The answer is advisory text generated by a language model: it can be wrong, and
it is general wellness information, not medical advice.
"""

