def render_latest_stored(user_id: int) -> None:
    ui.section("Latest stored recommendation", "What the dashboard reads and shows.", icon="🗂️")
    row = latest_recommendation(user_id)
    if row is None:
        ui.notice(
            "Nothing stored yet. Press the button above and the answer will be saved here (and on "
            "the dashboard).",
            tone="info",
            icon="💾",
        )
        return

    stale = coach_is_stale(row)
    if stale:
        ui.notice(
            f"This recommendation is older than {COACH_STALE_AFTER_DAYS} days. Your meals may have "
            "changed since then — run the coach again for a fresh answer.",
            tone="warning",
            icon="🕒",
        )
    ui.card(
        title=f"{friendly_timestamp(row.timestamp.isoformat())} · {row.source}",
        icon="💡",
        body_html=ui.html_raw(f"<div style='white-space:pre-wrap'>{_escape(row.recommendation_text)}</div>"),
    )
    if row.prompt:
        st.caption(f"Asked: “{row.prompt}”")
    st.caption(
        "AI-generated text stored with its model name so it is always distinguishable from the "
        "rule-based nutrition engine."
    )


def render_history(user_id: int) -> None:
    rows = stored_recommendations(user_id, limit=10)
    if len(rows) <= 1:
        return
    with st.expander(f"All stored recommendations ({len(rows)})"):
        for row in rows:
            st.markdown(f"**{friendly_timestamp(row.timestamp.isoformat())}** · `{row.source}`")
            if row.prompt:
                st.caption(f"Question: “{row.prompt}”")
            st.markdown(f"<div style='white-space:pre-wrap'>{_escape(row.recommendation_text)}</div>",
                        unsafe_allow_html=True)
            st.divider()


